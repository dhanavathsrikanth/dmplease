import { beforeEach, describe, expect, it, vi } from "vitest";

const WORKSPACE_ID = "11111111-2222-3333-4444-555555555555";
const OTHER_WORKSPACE_ID = "99999999-8888-7777-6666-555555555555";
const ASSET_ID = "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee";

const ENV: Record<string, string> = {
  R2_ACCOUNT_ID: "account-id",
  R2_ACCESS_KEY_ID: "access-key-id",
  R2_SECRET_ACCESS_KEY: "secret-access-key",
  R2_BUCKET_NAME: "bucket",
  R2_PUBLIC_CDN_URL: "https://cdn.example.com",
};

const presigner = vi.hoisted(() => ({
  getSignedUrl: vi.fn(async () => "https://r2.example.com/signed"),
}));

vi.mock("@/lib/config", () => ({
  cleanEnv: (name: string) => ENV[name] ?? "",
}));

vi.mock("@aws-sdk/s3-request-presigner", () => ({
  getSignedUrl: presigner.getSignedUrl,
}));

import { createAssetUpload, isWorkspaceAssetKey } from "@/lib/cloudflare/r2";

function validKey(workspaceId = WORKSPACE_ID): string {
  return `workspaces/${workspaceId}/messages/audio/${ASSET_ID}.mp3`;
}

beforeEach(() => {
  presigner.getSignedUrl.mockClear();
});

describe("isWorkspaceAssetKey", () => {
  it("accepts a key generated by createAssetUpload", () => {
    expect(isWorkspaceAssetKey(WORKSPACE_ID, validKey())).toBe(true);
  });

  it("rejects dot segments", () => {
    expect(
      isWorkspaceAssetKey(WORKSPACE_ID, `workspaces/${WORKSPACE_ID}/messages/../other`)
    ).toBe(false);
  });

  it("rejects double slashes", () => {
    expect(
      isWorkspaceAssetKey(WORKSPACE_ID, `workspaces/${WORKSPACE_ID}/messages//x`)
    ).toBe(false);
  });

  it("rejects percent-encoded traversal", () => {
    expect(
      isWorkspaceAssetKey(
        WORKSPACE_ID,
        `workspaces/${WORKSPACE_ID}/messages/audio/..%2f..%2fsecret`
      )
    ).toBe(false);
  });

  it("rejects a key belonging to another workspace", () => {
    expect(isWorkspaceAssetKey(WORKSPACE_ID, validKey(OTHER_WORKSPACE_ID))).toBe(
      false
    );
  });

  it("rejects a key containing a backslash", () => {
    expect(isWorkspaceAssetKey(WORKSPACE_ID, `${validKey()}\\`)).toBe(false);
  });
});

describe("createAssetUpload", () => {
  it("binds the validated size to the presigned upload", async () => {
    const sizeBytes = 12_345;

    const ticket = await createAssetUpload({
      workspaceId: WORKSPACE_ID,
      format: "audio",
      mimeType: "audio/mpeg",
      sizeBytes,
    });

    expect(presigner.getSignedUrl).toHaveBeenCalledTimes(1);
    const [, command] = presigner.getSignedUrl.mock.calls[0] as unknown as [
      unknown,
      { input: Record<string, unknown> },
    ];

    expect(command.input.ContentLength).toBe(sizeBytes);
    expect(command.input.Key).toBe(ticket.objectKey);
    expect(isWorkspaceAssetKey(WORKSPACE_ID, ticket.objectKey)).toBe(true);
  });
});
